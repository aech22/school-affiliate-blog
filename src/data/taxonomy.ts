// 絵文字は持たない（アイコンで意味を足せていないため）。
//
// 2026-09-06: SEO のため metaTitle と intro を追加した。
// ・label はサイト内のナビゲーション用の短い名前（画面に出る）。
// ・metaTitle は検索結果に出る <title> 用で、読者が実際に検索する語を含める。
// ・intro はカテゴリページ本文の導入で、そのカテゴリの記事が何に答えるのかを書く
//   （一覧だけの薄いページにしないため）。blurb は meta description に使う。
