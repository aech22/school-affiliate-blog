// gender 軸は無い。
//
// 2026-09-05: 読者像を「学び直し・働き方を変える社会人」に定義し直し、slug は変えずに
// ラベルと説明だけを広げた（判断ログ 2026-09-05「コドナビは総合化しない」）。
